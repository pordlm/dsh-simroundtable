export const COPY = { zh: ZH, en: EN };

/** Resolve a supported locale tag to its copy table. */
export function copyFor(locale) {
  return String(locale ?? "").toLowerCase().startsWith("zh") ? ZH : EN;
}

/**
 * Read the profile's locale preference, falling back to the process locale.
 *
 * DSH 0.2 no longer exposes `settings.get()`; the locale plugin now owns the
 * `locale` settings namespace and exposes its preference through the settings
 * form projection. `describe()` is the supported read path.
 */
export function detectLocale(ctx) {
  try {
    const described = ctx?.settings?.describe?.() ?? [];
    const entry = described.find((item) => String(item?.ns) === "locale")
      ?? described.find((item) => item?.value && typeof item.value === "object" && typeof item.value.preference === "string");
    const preference = entry?.value?.preference;
    if (typeof preference === "string" && preference.trim() !== "") {
      return preference.trim().toLowerCase().startsWith("zh") ? "zh" : "en";
    }
  } catch {
    // The settings service is optional for this plugin; fall through.
  }
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith("zh") ? "zh" : "en";
  } catch {
    return "en";
  }
}
